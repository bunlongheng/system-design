// Bakes the BUILT index.html into a JS module so the share function can serve the
// real SPA shell with per-design meta swapped in. A Vercel function cannot count
// on reading dist/, but it can import a module - same trick as lib/icon-data.js.
// Runs AFTER vite build (the asset hashes change every build).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(path.join(root, "dist", "index.html"), "utf8");
writeFileSync(
  path.join(root, "lib", "share-shell.js"),
  `// AUTO-GENERATED by scripts/gen-share-shell.mjs - do not edit.\nexport default ${JSON.stringify(html)};\n`,
);
console.log(`share-shell.js: ${html.length} bytes of index.html`);

// Build a data-URI manifest of every icon so the server-side SVG renderer can
// inline logos WITHOUT reading the filesystem at runtime (Vercel serverless has no
// access to public/ files). Import the JSON in lib/render-svg.js. Re-run whenever
// icons change: `node scripts/gen-icon-manifest.mjs` (also runs on prebuild).
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const DIRS = ["public/icons", "public/brand"];
const MIME = { svg: "image/svg+xml", png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", webp: "image/webp", gif: "image/gif" };

const manifest = {};
let count = 0, bytes = 0;
for (const dir of DIRS) {
  const abs = path.join(ROOT, dir);
  if (!existsSync(abs)) continue;
  for (const file of readdirSync(abs)) {
    const ext = file.split(".").pop().toLowerCase();
    if (!MIME[ext]) continue;
    const buf = readFileSync(path.join(abs, file));
    const key = "/" + path.relative(path.join(ROOT, "public"), path.join(abs, file)); // e.g. /icons/lambda.svg
    manifest[key] = `data:${MIME[ext]};base64,${buf.toString("base64")}`;
    count++; bytes += buf.length;
  }
}

// Write a JS module (not JSON) so every bundler/runtime imports it the same way -
// no JSON-import attributes that Vercel's function bundler chokes on.
const js = `// AUTO-GENERATED by scripts/gen-icon-manifest.mjs - do not edit.\nexport default JSON.parse(${JSON.stringify(JSON.stringify(manifest))})\n`;
writeFileSync(path.join(ROOT, "lib/icon-data.js"), js);
console.log(`icon manifest: ${count} icons, ${(bytes / 1024).toFixed(0)}KB source -> lib/icon-data.js`);
